import { describe, expect, it } from 'vitest'
import { parseStockContent, parseStockJson, parseStockSql } from './importStock'
import { stockToJson, stockToSql } from './exportStock'
import type { StockVariant } from '@shared/ipc'

const sampleVariants: StockVariant[] = [
  {
    id: 1,
    category: 'positive',
    sphereHundredths: 0,
    cylinderHundredths: 0,
    quantity: 5,
    createdAt: 1000,
    updatedAt: 1000
  },
  {
    id: 2,
    category: 'positive',
    sphereHundredths: 125,
    cylinderHundredths: -50,
    quantity: 3,
    createdAt: 1000,
    updatedAt: 1000
  },
  {
    id: 3,
    category: 'negative',
    sphereHundredths: -200,
    cylinderHundredths: -100,
    quantity: 2,
    createdAt: 1000,
    updatedAt: 1000
  }
]

describe('parseStockJson', () => {
  it('parses JSON generated by stockToJson', () => {
    const json = stockToJson(sampleVariants)
    const result = parseStockJson(json)

    expect(result.error).toBeUndefined()
    expect(result.items).toHaveLength(3)
    expect(result.items[0]).toEqual({
      category: 'positive',
      sphereHundredths: 0,
      cylinderHundredths: 0,
      quantity: 5
    })
    expect(result.items[1]).toEqual({
      category: 'positive',
      sphereHundredths: 125,
      cylinderHundredths: -50,
      quantity: 3
    })
    expect(result.items[2]).toEqual({
      category: 'negative',
      sphereHundredths: -200,
      cylinderHundredths: -100,
      quantity: 2
    })
  })

  it('parses user-friendly decimal JSON format', () => {
    const json = JSON.stringify([
      { sphere: 0.25, cylinder: -0.75, quantity: 4 },
      { sphere: -1.5, cylinder: -2, quantity: 1 }
    ])

    const result = parseStockJson(json)
    expect(result.error).toBeUndefined()
    expect(result.items).toHaveLength(2)
    expect(result.items[0]).toEqual({
      category: 'positive',
      sphereHundredths: 25,
      cylinderHundredths: -75,
      quantity: 4
    })
    expect(result.items[1]).toEqual({
      category: 'negative',
      sphereHundredths: -150,
      cylinderHundredths: -200,
      quantity: 1
    })
  })

  it('rejects invalid JSON syntax', () => {
    const result = parseStockJson('{ not valid json')
    expect(result.error).toContain('Sintaxe JSON inválida')
  })

  it('rejects off-quarter values', () => {
    const json = JSON.stringify([{ sphere: 0.12, cylinder: 0, quantity: 1 }])
    const result = parseStockJson(json)
    expect(result.error).toContain('0.25')
  })

  it('rejects positive cylinder values', () => {
    const json = JSON.stringify([{ sphere: 0, cylinder: 0.5, quantity: 1 }])
    const result = parseStockJson(json)
    expect(result.error).toContain('não pode ser positivo')
  })
})

describe('parseStockSql', () => {
  it('parses SQL output from stockToSql', () => {
    const sql = stockToSql(sampleVariants)
    const result = parseStockSql(sql)

    expect(result.error).toBeUndefined()
    expect(result.items).toHaveLength(3)
    expect(result.items[0]).toEqual({
      category: 'positive',
      sphereHundredths: 0,
      cylinderHundredths: 0,
      quantity: 5
    })
    expect(result.items[2]).toEqual({
      category: 'negative',
      sphereHundredths: -200,
      cylinderHundredths: -100,
      quantity: 2
    })
  })

  it('returns error when no valid INSERT statement is found', () => {
    const result = parseStockSql('SELECT * FROM lens_variants;')
    expect(result.error).toContain('Nenhum comando INSERT')
  })
})

describe('parseStockContent', () => {
  it('automatically detects JSON vs SQL format', () => {
    const json = stockToJson(sampleVariants)
    const sql = stockToSql(sampleVariants)

    expect(parseStockContent(json).items).toHaveLength(3)
    expect(parseStockContent(sql).items).toHaveLength(3)
  })
})
